import { feminineSurname, maskFragment, onlyFeminineOf, rankForRole, noNameWord, showNoName, titleCase, capFirst, placeCase, NP_TYPES, placeLabel, splitPlaceLabel, stripPlaceType, dayMonth } from "../src/names.ts";

let ok = 0, fail = 0;
function check(input, expected) {
  const got = titleCase(input);
  if (got === expected) { ok++; console.log(`  [ок]     «${input}» → «${got}»`); }
  else { fail++; console.log(`  [ОШИБКА] «${input}» → «${got}», ждали «${expected}»`); }
}
check("иван иванов", "Иван Иванов");
check("Иван Иванов", "Иван Иванов");
check("мария", "Мария");
check("  анна  петрова ", "  Анна  Петрова ");
check("анна-мария фон-дервиз", "Анна-Мария Фон-Дервиз");
check("евлампия васильева (сидорова)", "Евлампия Васильева (Сидорова)");
check("ёлкин", "Ёлкин");
check("иоаннъ", "Иоаннъ");
check("МакАртур", "МакАртур");
check("***", "***");
check("", "");

// «Имени нет»: копия records::is_no_name из крейта — те же примеры, что в его
// тесте no_name_and_surnames (src-tauri/core/src/records.rs).
function same(title, got, expected) {
  if (got === expected) { ok++; console.log(`  [ок]     ${title}`); }
  else { fail++; console.log(`  [ОШИБКА] ${title}: получили ${JSON.stringify(got)}, ждали ${JSON.stringify(expected)}`); }
}
for (const word of ["***", "*", "—", "?", "-", "Имя", "имя", "ИМЯ", "_", "...", "нрзб", "Нрзб.", "н/д", "Н/Д",
                    "неизвестно", "Неизв", "неизв.", "нет", "Нет", "б/и", "Б/и"]) same(`«${word}» — имени нет`, noNameWord(word), true);
for (const word of ["Иван", "2", "", "Имярек", "Им", "N", "*а", "Нета", "Неизвестнов", "нд"]) same(`«${word}» — не заглушка`, noNameWord(word), false);
same("«— Иванова Петрова» → «*** Иванова Петрова»", showNoName("— Иванова Петрова"), "*** Иванова Петрова");
same("«Имя Иванова» → «*** Иванова»", showNoName("Имя Иванова"), "*** Иванова");
same("«***» не меняется", showNoName("*** Иванова"), "*** Иванова");
same("обычное имя не меняется", showNoName("Иван Петров"), "Иван Петров");
same("цифра не меняется — её увидит окно сверки", showNoName("2 Иванова"), "2 Иванова");
same("пробел в начале сохраняется", showNoName(" ? Иванова"), " *** Иванова");
same("пустое поле не меняется", showNoName(""), "");
same("«нрзб Иванова» → «*** Иванова»", showNoName("Нрзб Иванова"), "*** Иванова");
// Фамилия отца — матери (Роман 06.10.2026).
for (const [his, hers] of [["Сидоров", "Сидорова"], ["Томский", "Томская"], ["Томилин", "Томилина"], ["Лисицын", "Лисицына"],
                           ["Соловьёв", "Соловьёва"], ["Трубецкой", "Трубецкая"], ["Белый", "Белая"], ["Толстой", "Толстая"],
                           ["Ивановъ", "Иванова"], ["Шевченко", "Шевченко"], ["Черных", "Черных"], ["Сова", "Сова"],
                           ["Палий", "Палий"], [" Петров ", "Петрова"]])
  same(`«${his}» → «${hers}»`, feminineSurname(his), hers);
// Заглавная буква в НП (Роман 07.10 и 08.10.2026): кроме названий с типа пункта.
const typing = (t) => placeCase(t, NP_TYPES, false), left = (t) => placeCase(t, NP_TYPES, true);
same("«борисоглебское» → заглавная сразу", typing("борисоглебское"), "Борисоглебское");
same("«а» → «А»", typing("а"), "А");
same("«по» — может стать «починок», не трогаем", typing("по"), "по");
same("«пок» — уже не тип: заглавная задним числом", typing("пок"), "Пок");
same("«починок » — ждём названия", typing("починок "), "починок ");
same("«починок Смыгарев» остаётся", typing("починок Смыгарев"), "починок Смыгарев");
same("«починок Смыгарев» при уходе остаётся", left("починок Смыгарев"), "починок Смыгарев");
same("«д.Балахонка, Заобнорская волость» остаётся", left("д.Балахонка, Заобнорская волость"), "д.Балахонка, Заобнорская волость");
same("«д.б» при наборе — заглавная у названия", typing("д.б"), "д.Б");
same("«починок смыгарев» → «починок Смыгарев»", typing("починок смыгарев"), "починок Смыгарев");
same("«д. балахонка» с пробелом → «д. Балахонка»", left("д. балахонка"), "д. Балахонка");
same("«починковский» — не тип «починок»", typing("починковский"), "Починковский");
same("«с-цо никольское» → «с-цо Никольское»", left("с-цо никольское"), "с-цо Никольское");
same("«де» — не тип", typing("де"), "Де");
same("«слобода» при наборе — ещё может быть типом", typing("слобода"), "слобода");
same("«слобода» при уходе — это название", left("слобода"), "Слобода");
same("«починок» при уходе — название", left("починок"), "Починок");
same("«слободка» — не тип", typing("слободка"), "Слободка");
same("«д.» при уходе без названия", left("д."), "Д.");
same("уже заглавная не меняется", left("Аксениха"), "Аксениха");
same("пробел в начале сохраняется", left(" баево"), " Баево");
same("пустое не меняется", left(""), "");
same("цифра в начале не меняется", left("2-й участок"), "2-й участок");
same("тип заглавными распознаётся", left("Починок Смыгарев"), "Починок Смыгарев");
same("губерния: «костромская» → «Костромская»", capFirst("костромская"), "Костромская");
same("губерния: «Область войска Донского» не меняется", capFirst("Область войска Донского"), "Область войска Донского");
same("волость: остальное не трогается", capFirst("ново-никольская"), "Ново-никольская");
// Название пункта с комментарием деревни-тёзки — те же примеры, что в тесте
// крейта place_comment (src-tauri/core/src/text.rs).
same("метка: «Хмельничное» + «Столпино»", placeLabel("Хмельничное", "Столпино"), "Хмельничное (Столпино)");
same("метка: пустой комментарий — просто название", placeLabel(" Хмельничное ", "  "), "Хмельничное");
same("дата списка: 1.9 → 01.09", dayMonth(1, 9), "01.09");
same("дата списка: 24.10", dayMonth(24, 10), "24.10");
same("дата списка: неизвестный день", dayMonth(null, 3), "?.03");
